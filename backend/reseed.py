import sqlite3
from contextlib import contextmanager
from pathlib import Path
from datetime import date, timedelta, datetime

DB_PATH = Path(__file__).parent / "smartpat.db"

@contextmanager
def get_conn():
    conn = sqlite3.connect(str(DB_PATH))
    conn.row_factory = sqlite3.Row
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()

TODAY = date(2026, 4, 25)

RATE = 50 / 60  # ₱50 per hour → per minute

def bill(mins):
    return round(max(25.0, mins * RATE), 2)

def s(slot, d, eh, em, duration_min=None):
    """Build a session row. duration_min=None means ongoing."""
    entry = f"{d} {eh:02d}:{em:02d}:00"
    if duration_min is None:
        return (slot, entry, None, None, None)
    exit_dt = datetime.fromisoformat(entry) + timedelta(minutes=duration_min)
    return (slot, entry, exit_dt.strftime("%Y-%m-%d %H:%M:%S"), duration_min, bill(duration_min))

def d(offset=0):
    return TODAY - timedelta(days=offset)

